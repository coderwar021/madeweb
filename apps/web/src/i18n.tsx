export function explainApiError(detail: string | undefined, fallback: "request" | "upload" = "request") {
  const locale = readLocale();
  if (!detail) return API_ERRORS[locale][fallback === "upload" ? "上传失败" : "请求失败"];
  const exact = API_ERRORS[locale][detail];
  if (exact) return exact;
  for (const pattern of API_PATTERNS) {
    const match = detail.match(pattern.re);
    if (match) return fill(pattern.text[locale], { label: translateLabel(locale, match[1]) });
  }
  return detail;
}

export function jobText(t: (key: MessageKey, vars?: Record<string, string | number>) => string, message: string) {
  const saved = message.match(/^已保存为 v(\d+)$/);
  if (saved) return t("savedVersion", { v: saved[1] });
  if (message === "这个功能已经在当前版本里了。") return t("alreadyThere");
  if (message.startsWith("我还不能安全地实现这个修改")) return t("cannotEdit");
  if (message.startsWith("已添加")) {
    const names = message
      .slice(3)
      .split("、")
      .map((name) => (FEATURES[name] ? t(FEATURES[name]) : name))
      .join(" · ");
    return t("addedFeatures", { names });
  }
  return message;
}

export function LanguageSwitch({ tone = "dark" }: { tone?: "dark" | "light" }) {
  const { locale, setLocale } = useI18n();
  const quiet = tone === "dark" ? "text-paper/40" : "text-black/35";
  const active = tone === "dark" ? "text-paper" : "text-black";
  return (
    <div className="flex items-center gap-2 text-xs">
      {(
        [
          ["zh", "中文"],
          ["ja", "日本語"],
          ["en", "EN"],
        ] as const
      ).map(([id, label]) => (
        <button key={id} type="button" onClick={() => setLocale(id)} aria-pressed={locale === id} className={locale === id ? active : quiet}>
          {label}
        </button>
      ))}
    </div>
  );
}
