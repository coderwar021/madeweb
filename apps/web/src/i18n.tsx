export type MessageKey = keyof typeof zh;

function readLocale(): Locale {
  const saved = localStorage.getItem(KEY);
  if (saved === "zh" || saved === "ja" || saved === "en") return saved;
  const lang = navigator.language.toLowerCase();
  if (lang.startsWith("ja")) return "ja";
  if (lang.startsWith("en")) return "en";
  return "zh";
}

function fill(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
}

const LocaleContext = createContext<{
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
} | null>(null);

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readLocale);
  useEffect(() => {
    document.documentElement.lang = locale === "zh" ? "zh-CN" : locale;
    localStorage.setItem(KEY, locale);
  }, [locale]);
  useEffect(() => {
    function onStorage(event: StorageEvent) {
      if (event.key === KEY && (event.newValue === "zh" || event.newValue === "ja" || event.newValue === "en")) setLocaleState(event.newValue);
    }
    window.addEventListener("storage", onStorage);
    return () => window.removeEventListener("storage", onStorage);
  }, []);
  const value = useMemo(
    () => ({
      locale,
      setLocale: setLocaleState,
      t: (key: MessageKey, vars?: Record<string, string | number>) => fill(messages[locale][key], vars),
    }),
    [locale],
  );
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useI18n() {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("locale missing");
  return value;
}

export function statusText(locale: Locale, value: string) {
  return STATUS[locale][value] || value;
}

export function translateLabel(locale: Locale, text: string) {
  if (locale === "zh") return text;
  return GLOSSARY[text]?.[locale] || text;
}

